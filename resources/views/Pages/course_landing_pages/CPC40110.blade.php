                    <h2>Description</h2>
                    <p>
                        This qualification is designed to meet the needs of builders and managers of small to medium-sized building businesses.
                    </p>
                    <p>
                        The builder may also be the appropriately licensed person with responsibility under the relevant building licensing authority in the State or Territory. Builder licensing varies across States and Territories and additional requirements to attainment of this qualification may be required.
                    </p>
                    <p>
                        Occupational titles may include:
                    </p>
                    <ul>
                        <li>Builder</li>
                        <li>Construction manager.</li>
                    </ul>

                    <p>The qualification has core unit of competency requirements that cover common skills for the construction industry.</p>

                    <p>The construction industry strongly affirms that training and assessment leading to recognition of skills must be undertaken in a real or very closely simulated workplace environment and this qualification requires all units of competency to be delivered in this context.</p>

                    <p>
                        Completion of the general induction training program specified by the National Code of Practice for Induction Training for Construction Work (ASCC 2007) is required before entering a construction work site. Achievement of unit CPCCOHS1001A covers this requirement.
                    </p>

                    <p>
                        Additional units of competency may be required to meet builder registration requirements in various States and Territories.
                    </p>

