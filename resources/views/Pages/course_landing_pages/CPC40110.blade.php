                    <h2>Packaging Rules</h2>
                    <p>To achieve this qualification, the candidate must demonstrate competency in:</p>
                    <ul>
                        <li>16 units of competency:</li>
                        <ul>
                            <li>
                                13 core units
                            </li>
                            <li>
                                3 elective units.
                            </li>
                        </ul>
                    </ul>

                    <p>The elective units must be selected as follows:</p>
                    <ul>
                        <li>all three elective units may be selected from the elective units listed below</li>
                        <li>two of the three elective units may be selected from Certificate III, Certificate IV or Diploma from another endorsed Training Package or from CPC08, provided that at least one unit is from Certificate IV and the industry context is maintained.</li>
                    </ul>

                    <p>Some units in this qualification may have prerequisite requirements, which must be met when packaging the qualification. Users are referred to the list of CPC08 units with prerequisite unit requirements available in this Training Package for this purpose.</p>

